const DICTS: Record<LangCode, Dict> = { en, hi, es, ar, fr };
const KEY = "medvision.lang";

type Vars = Record<string, string | number>;

interface Ctx {
  lang: LangCode;
  setLang: (l: LangCode) => void;
  /** Translate a UI key, with optional {placeholder} interpolation. */
  t: (key: string, vars?: Vars) => string;
  /** Translate a clinical term coming from data (condition, body part, fracture type). */
  tt: (term?: string | null) => string;
  dir: "ltr" | "rtl";
}

function interpolate(value: string, vars?: Vars) {
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`));
}

const I18nContext = createContext<Ctx>({
  lang: "en",
  setLang: () => {},
  t: (k, v) => interpolate(en[k] ?? k, v),
  tt: (term) => term ?? "",
  dir: "ltr",
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem(KEY) as LangCode | null;
    if (stored && stored in DICTS) setLangState(stored);
  }, []);

  const dir: "ltr" | "rtl" = lang === "ar" ? "rtl" : "ltr";

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
  }, [lang, dir]);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    window.localStorage.setItem(KEY, l);
  }, []);

  const t = useCallback(
    (key: string, vars?: Vars) => interpolate(DICTS[lang][key] ?? en[key] ?? key, vars),
    [lang],
  );

  const tt = useCallback(
    (term?: string | null) => {
      if (!term) return "";
      return DICTS[lang][`term.${term}`] ?? en[`term.${term}`] ?? term;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t, tt, dir }), [lang, setLang, t, tt, dir]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  return useContext(I18nContext);
}
